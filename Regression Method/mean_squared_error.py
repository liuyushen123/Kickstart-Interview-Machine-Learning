from sklearn.metrics import mean_squared_error

y_true = [100, 150, 200]
y_pred = [110, 140, 250]

# 计算 MSE
mse = mean_squared_error(y_true, y_pred)
print(f"MSE: {mse}")

# --- 拆解它的底层计算过程 ---
# 1. 先算出每个预测的误差：
#    (100 - 110) = -10
#    (150 - 140) = 10
#    (200 - 250) = -50

# 2. 把误差统统“平方”（消除负号，同时放大“大错误”）：
#    (-10)² = 100
#    (10)²  = 100
#    (-50)² = 2500   <-- 看，50的误差被放大了成倍！

# 3. 最后求这些平方值的平均数：
#    (100 + 100 + 2500) / 3 = 2700 / 3 = 900.0


